#pragma once
#include "openkal/client/UiDocument.h"
#include "openkal/client/UiView.h"
#include "openkal/protocol/Trade.h"

#include <optional>

namespace openkal::client {
    class UiLayoutStore;
    class ItemDb;
    /** Modal trade inventory, two twelve-cell offers and revision-bound acceptance. */
    class TradeWindow final {
      public:
        /** @param layouts Shared universal UI layouts. */
        explicit TradeWindow(UiLayoutStore& layouts);

        /** @param state Authoritative snapshot. @param serial Snapshot sequence.
         * @param width Viewport width. @param height Viewport height. @param scale Preferred scale.
         */
        void update(const protocol::TradeState& state,
                    std::uint64_t serial,
                    float width,
                    float height,
                    float scale);

        /** @param input Unmuted input. @param ui Widget helpers.
         * @return Trade command generated by editing or acceptance, if any. */
        [[nodiscard]] std::optional<protocol::TradeRequest> handle(const engine::FrameInput& input,
                                                                   WidgetTools& ui);

        /** Clears the pending command after a transport failure. */
        void send_failed();

        /** @param engine Renderer. @param ui Widget helpers. @param font TrueType font.
         * @param items Item catalog. @param input Unmuted pointer input. */
        void draw(engine::IEngine& engine,
                  WidgetTools& ui,
                  const FreetypeFont& font,
                  const ItemDb& items,
                  const engine::FrameInput& input) const;

      private:
        class Host;
        [[nodiscard]] UiVarMap variables() const;
        [[nodiscard]] UiHit
        hit(const engine::FrameInput& input, WidgetTools& ui, bool quantity = false) const;
        [[nodiscard]] const protocol::TradeItem* item_at(std::string_view bind, int slot) const;
        [[nodiscard]] int remaining(std::uint32_t iid) const;
        [[nodiscard]] int free_offer_slot() const;
        [[nodiscard]] std::optional<protocol::TradeRequest> command(protocol::TradeCommand kind);
        [[nodiscard]] std::optional<protocol::TradeRequest>
        edit_item(std::uint32_t iid, int slot, bool own);
        [[nodiscard]] std::optional<protocol::TradeRequest> apply_quantity(int count);
        [[nodiscard]] std::optional<protocol::TradeRequest> publish();
        void reset_drag();
        void restore_offer();
        UiLayoutStore& m_layouts;
        UiDocument m_document, m_quantity_document;
        protocol::TradeState m_state;
        std::uint64_t m_serial = 0;
        std::vector<protocol::TradeAmount> m_offer;
        std::string m_money = "0", m_quantity = "1", m_notice;
        std::uint32_t m_next_operation = 1, m_pending_operation = 0;
        bool m_money_focus = false, m_money_pristine = true, m_money_dirty = false;
        std::uint32_t m_quantity_iid = 0;
        int m_quantity_slot = 0, m_quantity_max = 0;
        bool m_quantity_own = false, m_quantity_pristine = true;
        std::uint32_t m_drag_iid = 0, m_last_click_iid = 0;
        bool m_drag_own = false, m_drag_moved = false, m_last_click_own = false;
        float m_drag_x = 0, m_drag_y = 0;
        double m_clock = 0, m_last_click = -1;
        float m_scroll = 0, m_max_scroll = 0;
        float m_x = 0, m_y = 0, m_scale = 1, m_screen_w = 0, m_screen_h = 0;
        float m_quantity_x = 0, m_quantity_y = 0;
    };
}  // namespace openkal::client
